os.makedirs('docs/submission/figures', exist_ok=True)

# Load metrics
with open('results/metrics_v2/eval_v2.json', 'r') as f:
    eval_metrics = json.load(f)

with open('results/metrics_v2/lead_time.json', 'r') as f:
    lead_time_data = json.load(f)

with open('results/metrics_v2/shap_and_permutation.json', 'r') as f:
    shap_data = json.load(f)


def setup_theme(dark=False, poster=False):
    plt.style.use('default')
    bg = '#0b132b' if dark else '#ffffff'
    fg = '#f8fafc' if dark else '#0f172a'
    grid = '#1c2541' if dark else '#e2e8f0'
    base_font = 20 if poster else 10
    plt.rcParams.update({
        'font.size': base_font,
        'axes.labelsize': base_font + 2,
        'axes.titlesize': base_font + 3,
        'xtick.labelsize': base_font,
        'ytick.labelsize': base_font,
        'legend.fontsize': base_font - 1,
        'figure.facecolor': bg,
        'axes.facecolor': bg,
        'axes.edgecolor': grid if dark else '#cbd5e1',
        'axes.labelcolor': fg,
        'xtick.color': fg,
        'ytick.color': fg,
        'text.color': fg,
        'grid.color': grid,
        'figure.dpi': 300
    })
    return bg, fg, grid


