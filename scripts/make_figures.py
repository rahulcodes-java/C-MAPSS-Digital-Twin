    ax.add_patch(rect_rf)
    ax.text(61, 15, "Snapshot Classifiers", ha='center', va='center', weight='bold', color=fg)
    ax.text(61, 10, "Input: 1 \u00d7 21 Single Cycle Vector\n\u2022 Random Forest (3 Health Stages)\n\u2022 Isolation Forest (Novelty Outliers)", ha='center', va='center', color=fg, fontsize=plt.rcParams['font.size']-3)

    # Output Arrows
    ax.annotate('', xy=(79, 32), xytext=(74, 32),
                arrowprops=dict(facecolor='#0284c7', edgecolor='#0284c7', width=1.8, headwidth=7))
    ax.annotate('', xy=(79, 12), xytext=(74, 12),
                arrowprops=dict(facecolor='#059669', edgecolor='#059669', width=1.8, headwidth=7))

