def make_pipeline_diagram(dark=False, poster=False):
    bg, fg, grid = setup_theme(dark, poster)
    fig, ax = plt.subplots(figsize=(10, 4.2))
    ax.set_xlim(0, 100)
    ax.set_ylim(0, 42)
    ax.axis('off')

    box_bg = '#1c2541' if dark else '#f1f5f9'
    border = '#38bdf8' if dark else '#2563eb'
    hl_bg = '#1e293b' if dark else '#e2e8f0'

    # Step 1: Raw Telemetry
    rect1 = patches.FancyBboxPatch((2, 13), 20, 18, boxstyle="round,pad=1.0", fc=box_bg, ec=border, lw=1.5)
    ax.add_patch(rect1)
    ax.text(12, 26, "Raw Telemetry", ha='center', va='center', weight='bold', color=fg)
    ax.text(12, 20, "21 Turbofan Sensors\n(C-MAPSS Data)", ha='center', va='center', color=fg, fontsize=plt.rcParams['font.size']-2)

    # Arrow 1 -> Branch
    ax.annotate('', xy=(28, 22), xytext=(23, 22),
                arrowprops=dict(facecolor=border, edgecolor=border, width=2, headwidth=8))

    # MinMax Scaler
    rect_scale = patches.FancyBboxPatch((28, 14), 14, 16, boxstyle="round,pad=0.8", fc=hl_bg, ec=border, lw=1.2)
    ax.add_patch(rect_scale)
    ax.text(35, 23, "MinMax\nScaling", ha='center', va='center', weight='bold', color=fg)
    ax.text(35, 17, "(Fitted on Train)", ha='center', va='center', color=fg, fontsize=plt.rcParams['font.size']-3)

    # Branch arrows
    # Top Branch -> LSTM (50x21 Window)
    ax.annotate('', xy=(49, 32), xytext=(43, 25),
                arrowprops=dict(facecolor='#0284c7', edgecolor='#0284c7', width=1.8, headwidth=7))
    # Bottom Branch -> RF & IForest (1x21 Vector)
    ax.annotate('', xy=(49, 12), xytext=(43, 19),
                arrowprops=dict(facecolor='#059669', edgecolor='#059669', width=1.8, headwidth=7))

    # LSTM Block
    rect_lstm = patches.FancyBboxPatch((49, 25), 24, 14, boxstyle="round,pad=0.8", fc=box_bg, ec='#0284c7', lw=1.5)
    ax.add_patch(rect_lstm)
    ax.text(61, 34, "LSTM RUL Regressor", ha='center', va='center', weight='bold', color=fg)
    ax.text(61, 29, "Input: 50 \u00d7 21 Sliding Window\nArchitecture: 128 \u2192 64 \u2192 32 Dense", ha='center', va='center', color=fg, fontsize=plt.rcParams['font.size']-3)

    # RF & IForest Block
