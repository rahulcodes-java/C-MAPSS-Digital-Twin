# Figure 7: Confusion Matrices (FD001 Test)
# -------------------------------------------------------------
def make_confusion_matrices(dark=False, poster=False):
    bg, fg, grid = setup_theme(dark, poster)
    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(9.5, 4.2))

    cm_rf = np.array(eval_metrics['classification_3stage']['FD001']['rf']['confusion_matrix'])
    cm_lstm = np.array(eval_metrics['classification_3stage']['FD001']['lstm_derived']['confusion_matrix'])
    classes = ['Healthy', 'Degrading', 'Critical']

    cmap = 'Blues' if not dark else 'viridis'

    for ax, cm, title in [(ax1, cm_rf, 'Random Forest (Macro-F1: 0.7303)'), (ax2, cm_lstm, 'LSTM-Derived (Macro-F1: 0.8197)')]:
        im = ax.imshow(cm, interpolation='nearest', cmap=cmap)
        ax.set_title(title, fontsize=plt.rcParams['font.size'])
        tick_marks = np.arange(len(classes))
        ax.set_xticks(tick_marks)
        ax.set_xticklabels(classes, rotation=25)
        ax.set_yticks(tick_marks)
        ax.set_yticklabels(classes)
        ax.set_ylabel('True Stage')
        ax.set_xlabel('Predicted Stage')

        # Add text in each cell
        thresh = cm.max() / 2.
        for i in range(cm.shape[0]):
            for j in range(cm.shape[1]):
                val = cm[i, j]
                color = "white" if val > thresh else ("black" if not dark else "white")
                ax.text(j, i, f"{val:,}", ha="center", va="center", color=color, fontsize=plt.rcParams['font.size']-2, weight='bold')

    suffix = ('_poster' if poster else '') + ('_dark' if dark else '_light')
    path = f'docs/submission/figures/confusion_matrices{suffix}.png'
    plt.tight_layout()
    plt.savefig(path, dpi=300, facecolor=fig.get_facecolor(), bbox_inches='tight')
    plt.close()
    print(f"Saved {path}")


def generate_all_figures():
    for dark in [False, True]:
        for poster in [False, True]:
            make_pipeline_diagram(dark=dark, poster=poster)
            make_critical_f1_chart(dark=dark, poster=poster)
            make_shap_top10(dark=dark, poster=poster)
            make_shap_by_area(dark=dark, poster=poster)
            make_lead_time_distribution(dark=dark, poster=poster)
            make_confusion_matrices(dark=dark, poster=poster)


if __name__ == '__main__':
    generate_all_figures()
