# Figure 4: SHAP by Engine Area with SD
# -------------------------------------------------------------
def make_shap_by_area(dark=False, poster=False):
    bg, fg, grid = setup_theme(dark, poster)
    fig, ax = plt.subplots(figsize=(7.5, 4.2))

    area_runs = sorted(shap_data['shap_area_5runs'], key=lambda x: x['mean_pct'], reverse=True)
    areas = [x['area'] for x in reversed(area_runs) if x['mean_pct'] > 0.0]
    means = [x['mean_pct'] for x in reversed(area_runs) if x['mean_pct'] > 0.0]
    sds = [x['sd_pct'] for x in reversed(area_runs) if x['mean_pct'] > 0.0]

    colors = ['#38bdf8' if a == 'HPC' else ('#059669' if not dark else '#34d399') for a in areas]

    y_pos = np.arange(len(areas))
    ax.barh(y_pos, means, xerr=sds, align='center', color=colors, ecolor='#dc2626' if not dark else '#f87171', capsize=4, alpha=0.9)
    ax.set_yticks(y_pos)
    ax.set_yticklabels(areas)
    ax.set_xlabel('Total Subassembly SHAP Contribution (% \u00b1 SD)')
    ax.set_title('Engine Subassembly Attribution (FD001 HPC Degradation)')
    ax.grid(True, linestyle='--', alpha=0.4, axis='x')

    for i, (m, s) in enumerate(zip(means, sds)):
        ax.text(m + s + 1.0, i, f"{m:.2f} \u00b1 {s:.2f}%", va='center', fontsize=plt.rcParams['font.size']-2, color=fg)

    ax.set_xlim(0, max(means) + 9)

    suffix = ('_poster' if poster else '') + ('_dark' if dark else '_light')
    path = f'docs/submission/figures/shap_by_area{suffix}.png'
    plt.tight_layout()
    plt.savefig(path, dpi=300, facecolor=fig.get_facecolor(), bbox_inches='tight')
    plt.close()
    print(f"Saved {path}")


