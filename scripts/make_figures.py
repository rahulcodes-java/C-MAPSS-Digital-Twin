# Figure 6: Lead-Time Delay Distribution (RF vs LSTM)
# -------------------------------------------------------------
def make_lead_time_distribution(dark=False, poster=False):
    bg, fg, grid = setup_theme(dark, poster)
    fig, ax = plt.subplots(figsize=(7.5, 4.2))

    # Boxplot of degrading delays and paired differences across all 100 engines
    # Load raw records from edf by running a lightweight extraction or using metrics
    train_df = pd.read_csv('data/processed/FD001_train_cleaned.csv')
    with open('results/metrics_v2/lead_time.json', 'r') as f:
        lt = json.load(f)

    c_all = lt['cohort_all']
    # Summarize with horizontal bar / interval display of median and IQR
    labels = [
        'RF Degrading Delay\n(Detection - True)',
        'LSTM Degrading Delay\n(Detection - True)',
        'Paired Advantage\n(RF Delay - LSTM Delay)'
    ]
    medians = [
        c_all['degrading_rf']['median_delay'],
        c_all['degrading_lstm']['median_delay'],
        c_all['paired_degrading_rf_minus_lstm']['median']
    ]
    iqrs = [
        c_all['degrading_rf']['iqr_delay'],
        c_all['degrading_lstm']['iqr_delay'],
        c_all['paired_degrading_rf_minus_lstm']['iqr']
    ]
    means = [
        c_all['degrading_rf']['mean_delay'],
        c_all['degrading_lstm']['mean_delay'],
        c_all['paired_degrading_rf_minus_lstm']['mean']
    ]

    y_pos = np.arange(len(labels))
    colors = ['#059669' if not dark else '#34d399', '#0284c7' if not dark else '#38bdf8', '#d97706' if not dark else '#fbbf24']

    ax.barh(y_pos, medians, xerr=np.array(iqrs)/2.0, color=colors, alpha=0.85, capsize=6, height=0.55)
    ax.axvline(0, color=fg, linestyle=':', alpha=0.7)
    ax.set_yticks(y_pos)
    ax.set_yticklabels(labels)
    ax.set_xlabel('Flight Cycles (Median \u00b1 Half-IQR Across 100 Engines)')
    ax.set_title('Degradation Stage Detection Delay and Paired Lead Time')
    ax.grid(True, linestyle='--', alpha=0.4, axis='x')

    for i, (med, mn) in enumerate(zip(medians, means)):
        pos_offset = 2.0 if med >= 0 else -18.0
        ax.text(med + pos_offset, i, f"Median: {med:.1f}c\n(Mean: {mn:.1f}c)", va='center', fontsize=plt.rcParams['font.size']-3, color=fg)

    suffix = ('_poster' if poster else '') + ('_dark' if dark else '_light')
    path = f'docs/submission/figures/lead_time_distribution{suffix}.png'
    plt.tight_layout()
    plt.savefig(path, dpi=300, facecolor=fig.get_facecolor(), bbox_inches='tight')
    plt.close()
    print(f"Saved {path}")


