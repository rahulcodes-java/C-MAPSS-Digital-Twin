def make_critical_f1_chart(dark=False, poster=False):
    bg, fg, grid = setup_theme(dark, poster)
    fig, ax = plt.subplots(figsize=(7.5, 4.2))

    datasets = ['FD001', 'FD002', 'FD003', 'FD004']
    rf_f1s = [eval_metrics['classification_critical_binary'][ds]['rf']['f1'] for ds in datasets]
    lstm_f1s = [eval_metrics['classification_critical_binary'][ds]['lstm_derived']['f1'] for ds in datasets]
    iforest_f1s = [eval_metrics['classification_critical_binary'][ds]['iforest']['f1'] for ds in datasets]

    x = np.arange(len(datasets))
    width = 0.26

    c_lstm = '#0284c7' if not dark else '#38bdf8'
    c_rf = '#059669' if not dark else '#34d399'
    c_if = '#d97706' if not dark else '#fbbf24'

    rects1 = ax.bar(x - width, lstm_f1s, width, label='LSTM (Sequence Window)', color=c_lstm)
    rects2 = ax.bar(x, rf_f1s, width, label='Random Forest (Snapshot)', color=c_rf)
    rects3 = ax.bar(x + width, iforest_f1s, width, label='Isolation Forest (Unsupervised)', color=c_if)

    ax.set_ylabel('Critical-Class F1 Score')
    ax.set_title('Critical Degradation Class (RUL \u2264 30) F1 per Dataset')
    ax.set_xticks(x)
    ax.set_xticklabels(datasets)
    ax.set_ylim(0, 1.0)
    ax.legend(loc='upper right', framealpha=0.85)
    ax.grid(True, linestyle='--', alpha=0.4, axis='y')

    # Add bar labels for FD001
    ax.annotate(f"{lstm_f1s[0]:.3f}", xy=(x[0] - width, lstm_f1s[0] + 0.02), ha='center', fontsize=plt.rcParams['font.size']-2)
    ax.annotate(f"{rf_f1s[0]:.3f}", xy=(x[0], rf_f1s[0] + 0.02), ha='center', fontsize=plt.rcParams['font.size']-2)
    ax.annotate(f"{iforest_f1s[0]:.3f}", xy=(x[0] + width, iforest_f1s[0] + 0.02), ha='center', fontsize=plt.rcParams['font.size']-2)

    suffix = ('_poster' if poster else '') + ('_dark' if dark else '_light')
    path = f'docs/submission/figures/critical_f1_comparison{suffix}.png'
    plt.tight_layout()
    plt.savefig(path, dpi=300, facecolor=fig.get_facecolor(), bbox_inches='tight')
    plt.close()
    print(f"Saved {path}")


