# Figure 3: SHAP Top-10 with SD Error Bars
# -------------------------------------------------------------
def make_shap_top10(dark=False, poster=False):
    bg, fg, grid = setup_theme(dark, poster)
    fig, ax = plt.subplots(figsize=(7.5, 4.5))

    sensor_runs = sorted(shap_data['shap_sensor_5runs'], key=lambda x: x['mean_pct'], reverse=True)[:10]
    sensor_names = [x['sensor'] for x in reversed(sensor_runs)]
    means = [x['mean_pct'] for x in reversed(sensor_runs)]
    sds = [x['sd_pct'] for x in reversed(sensor_runs)]
    areas = [x['area'] for x in reversed(sensor_runs)]

    bar_color = '#2563eb' if not dark else '#38bdf8'
    err_color = '#dc2626' if not dark else '#f87171'

    y_pos = np.arange(len(sensor_names))
    ax.barh(y_pos, means, xerr=sds, align='center', color=bar_color, ecolor=err_color, capsize=4, alpha=0.85)
    ax.set_yticks(y_pos)
    labels = [f"{s} ({a})" for s, a in zip(sensor_names, areas)]
    ax.set_yticklabels(labels)
    ax.set_xlabel('Mean SHAP Importance (% \u00b1 SD across 5 seeds)')
    ax.set_title('Top 10 Sensors by TreeSHAP Attribution (FD001)')
    ax.grid(True, linestyle='--', alpha=0.4, axis='x')

    # Annotate values
    for i, (m, s) in enumerate(zip(means, sds)):
        ax.text(m + s + 0.3, i, f"{m:.2f} \u00b1 {s:.2f}%", va='center', fontsize=plt.rcParams['font.size']-3, color=fg)

    ax.set_xlim(0, max(means) + 4)

    suffix = ('_poster' if poster else '') + ('_dark' if dark else '_light')
    path = f'docs/submission/figures/shap_top10{suffix}.png'
    plt.tight_layout()
    plt.savefig(path, dpi=300, facecolor=fig.get_facecolor(), bbox_inches='tight')
    plt.close()
    print(f"Saved {path}")


